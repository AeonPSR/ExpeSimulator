// A project is worked by a RELAY of two players who alternate 50/50. Each roll
// advances completion by that player's own gain; a roll costs 2 AP. Each player
// rolls at their own efficiency:
//
//   playerMin  = efficiency + priority + 4 × playerSkills
//   playerMax  = floor(playerMin × 1.5)          (the game rounds the max DOWN)
//   playerGain = (playerMin + playerMax) / 2  → "average"  |  playerMax  → "nof"
//   relayGain  = (playerGainA + playerGainB) / 2
//   AP         = ceil(100 / relayGain) × 2
//
//   playerSkills : how many of the project's TWO bonus skills that player has (0-2)
//   priority     : normal → +0 | prioritised → +1   (applies to both players)
//
// Fields are indexed by the TOTAL matching skills across the pair (0-4), split
// as evenly as possible: 0→0+0, 1→1+0, 2→1+1, 3→2+1, 4→2+2. (The 2+0 split for
// the "2" bucket is deliberately ignored — it only diverges from 1+1 if the
// skill bonus stops being even, and we treat them as identical.)
//
// The twenty fields (X = 0..4 total skills):
//   averageAP_Xskill      : priority 0, gain = average
//   nofAP_Xskill          : priority 0, gain = max
//   priorityAP_Xskill     : priority 1, gain = average
//   nof_priorityAP_Xskill : priority 1, gain = max
//
// Not every type carries every family:
//   neron    → all four families
//   research → averageAP + priorityAP  (no "nof" variants)
//   pilgred  → averageAP only          (no "nof", no priority)
//
